// Fills content/template.md with content/snippets.json and writes stories.json
// (27 stories × 5 pages) to content/, and the copy bundled by app/ (the web app and its /api).
// Usage: node scripts/build-stories.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const template = readFileSync(join(root, 'content/template.md'), 'utf8');
const snippets = JSON.parse(readFileSync(join(root, 'content/snippets.json'), 'utf8'));

// Each "## Page N" section is narration lines followed by one "sfx:" line.
const pageTemplates = template
  .split(/^## Page \d+.*$/m)
  .slice(1)
  .map((section) => {
    const lines = section.split('\n').map((l) => l.trim()).filter(Boolean);
    const sfxLine = lines.find((l) => l.startsWith('sfx:'));
    if (!sfxLine) throw new Error('Every page needs an sfx: line');
    return {
      text: lines.filter((l) => !l.startsWith('sfx:')).join('\n'),
      sfx: sfxLine.slice(4).trim(),
    };
  });
if (pageTemplates.length !== 5) throw new Error(`Expected 5 pages, found ${pageTemplates.length}`);

function fill(text, slots) {
  // Two passes, so snippets can use slots themselves (e.g. "{hero}" inside sidekick.scared).
  let out = text;
  for (let i = 0; i < 2; i++) {
    out = out.replace(/\{(\w+)\}/g, (m, key) => {
      if (!(key in slots)) throw new Error(`Unknown slot ${m}`);
      return slots[key];
    });
  }
  return out;
}

// Captions are the narration without audio tags.
const toCaption = (text) => text.replace(/\[[^\]]*\]\s*/g, '').replace(/\s+/g, ' ').trim();

const stories = {};
for (const [heroId, hero] of Object.entries(snippets.heroes)) {
  for (const [placeId, place] of Object.entries(snippets.places)) {
    for (const [sidekickId, sidekick] of Object.entries(snippets.sidekicks)) {
      const slots = {
        hero: hero.name,
        hero_catchphrase: hero.catchphrase,
        hero_trick: hero.trick,
        hero_trick_sfx: hero.trick_sfx,
        hero_party: hero.party,
        place: place.the,
        place_line: place.line,
        place_arrive_sfx: place.arrive_sfx,
        place_noise: place.noise,
        place_noise_sfx: place.noise_sfx,
        place_culprit: place.culprit,
        place_party_sfx: place.party_sfx,
        sidekick: sidekick.name,
        sidekick_scared: sidekick.scared,
        sidekick_scared_sfx: sidekick.scared_sfx,
        sidekick_happy: sidekick.happy,
      };
      const id = `${heroId}-${placeId}-${sidekickId}`;
      stories[id] = {
        id,
        hero: heroId,
        place: placeId,
        sidekick: sidekickId,
        title: `${hero.name}, ${sidekick.name} and the ${place.name}`,
        pages: pageTemplates.map((p) => {
          const text = fill(p.text, slots);
          return { text, caption: toCaption(text), sfx: fill(p.sfx, slots) };
        }),
      };
    }
  }
}

// The pickers list the choices in snippet order.
const choices = Object.fromEntries(
  ['heroes', 'places', 'sidekicks'].map((kind) => [
    kind,
    Object.entries(snippets[kind]).map(([id, s]) => ({ id, name: s.name })),
  ]),
);

const json = JSON.stringify({ version: 1, choices, stories }, null, 2) + '\n';
for (const out of ['content/stories.json', 'app/src/stories.json']) {
  writeFileSync(join(root, out), json);
}
console.log(`Wrote ${Object.keys(stories).length} stories × ${pageTemplates.length} pages`);

// A readable copy for reviewing the text without opening JSON.
const md = ['# All 27 stories', '', 'Generated by `npm run stories` from template.md and snippets.json. Edit those, not this file.', ''];
for (const story of Object.values(stories)) {
  md.push(`## ${story.title}`, '', `\`${story.id}\``, '');
  story.pages.forEach((p, i) => md.push(`**Page ${i + 1}.** ${p.text.replace(/\n/g, ' ')}`, '', `_Sound effect: ${p.sfx}_`, ''));
}
writeFileSync(join(root, 'content/STORIES.md'), md.join('\n'));
